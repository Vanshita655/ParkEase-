-- 5) Anonymous community parking reports linked to the signed-in account.
create table if not exists public.parking_reports (
  id bigint generated by default as identity primary key,
  user_id uuid not null references auth.users(id) on delete cascade,
  route text not null,
  destination text,
  status text not null check (status in ('available','full')),
  created_at timestamptz not null default now()
);

alter table public.parking_reports enable row level security;

