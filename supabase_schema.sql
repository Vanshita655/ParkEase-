-- ParkEase database setup for Supabase
-- Run this entire file in Supabase Dashboard -> SQL Editor.
-- This schema uses Supabase Auth for passwords/sessions and Postgres RLS
-- for user-owned data.

create extension if not exists pgcrypto;

-- 1) User profile
create table if not exists public.profiles (
  id uuid primary key references auth.users(id) on delete cascade,
  full_name text not null,
  university_id text,
  department text,
  created_at timestamptz not null default now()
);

alter table public.profiles enable row level security;

drop policy if exists "Users can view own profile" on public.profiles;
create policy "Users can view own profile"
on public.profiles for select
to authenticated
using ((select auth.uid()) = id);

drop policy if exists "Users can insert own profile" on public.profiles;
create policy "Users can insert own profile"
on public.profiles for insert
to authenticated
with check ((select auth.uid()) = id);

drop policy if exists "Users can update own profile" on public.profiles;
create policy "Users can update own profile"
on public.profiles for update
to authenticated
using ((select auth.uid()) = id)
with check ((select auth.uid()) = id);

-- 2) Automatically create a profile after Supabase Auth signup.
create schema if not exists private;

create or replace function private.handle_new_user()
returns trigger
language plpgsql
security definer
set search_path = ''
as $$
begin
  insert into public.profiles (id, full_name, university_id, department)
  values (
    new.id,
    coalesce(new.raw_user_meta_data->>'full_name', 'ParkEase User'),
    new.raw_user_meta_data->>'university_id',
    new.raw_user_meta_data->>'department'
  )
  on conflict (id) do nothing;
  return new;
end;
$$;

revoke all on function private.handle_new_user() from public, anon, authenticated;

drop trigger if exists on_auth_user_created on auth.users;
create trigger on_auth_user_created
after insert on auth.users
for each row execute procedure private.handle_new_user();

-- 3) Historical route/parking patterns used by the prototype.
create table if not exists public.route_patterns (
  id bigint generated by default as identity primary key,
  route text not null,
  time_slot text not null,
  congestion_level text not null check (congestion_level in ('Low','Medium','High')),
  parking_difficulty text not null check (parking_difficulty in ('Low','Medium','High')),
  informal_parking_zone text not null,
  avg_extra_minutes integer not null default 0,
  carpool_pool_size integer not null default 0,
  unique(route, time_slot)
);

alter table public.route_patterns enable row level security;

drop policy if exists "Route patterns are readable" on public.route_patterns;
create policy "Route patterns are readable"
on public.route_patterns for select
to anon, authenticated
using (true);

