-- 7) Explicit least-privilege grants for the browser Data API.
revoke all on table public.profiles, public.route_patterns, public.trip_history,
  public.parking_reports, public.saved_spots from anon, authenticated;

grant select on public.route_patterns to anon, authenticated;

grant select, insert, update on public.profiles to authenticated;
grant select, insert, delete on public.trip_history to authenticated;
grant select, insert on public.parking_reports to authenticated;
grant select, insert, delete on public.saved_spots to authenticated;

-- Identity columns used by inserts.
grant usage, select on all sequences in schema public to authenticated;
